"""Name heuristics for nets and pins: grounds, rails, voltages, auto names and pin roles."""

from __future__ import annotations

import re

_SEP = re.compile(r"[^A-Z0-9.+]+")
_DOT = re.compile(r"(?<!\d)\.|\.(?!\d)")

_GROUND_TOKEN = re.compile(
    r"^(?:[ADPSE]|ISO|SIG|PWR|ANA|DIG)?(?:GND|GROUND|VSS)(?:[ADPSE]|IO|ISO|PWR|ANA|DIG|\d{1,3})?$|^0V$"
)
_CHASSIS_TOKEN = re.compile(r"^(?:CHASSIS|CHGND|CGND|EARTH|PE|SHIELD|SHLD|FGND)\d*$")
_VOLT_TOKEN = re.compile(
    r"^[+-]?(?:"
    r"(?P<a>\d+)[VP](?P<b>\d+)V?"
    r"|(?P<c>\d+(?:\.\d+)?)V"
    r"|V(?P<d>\d+)P(?P<e>\d+)"
    r"|(?P<sign>[PN])(?P<f>\d+)V(?P<g>\d*)"
    r")(?P<suffix>[A-Z]{0,4})$"
)
_SUPPLY_WORDS = re.compile(
    r"^(?:[ADP]?VCC\w*|[ADP]?VDD\w*|VEE|VBUS|VBAT\w*|VIN|VSYS|VCORE|IOVDD|PVIN|VDDQ|VPP|"
    r"VREF\w*|VMAIN|VPWR|VSUPPLY|VCCINT|VCCAUX|VLED)[+-]?$"
)
_CONTROL_WORDS = {
    "EN", "ENA", "ENABLE", "PG", "PGOOD", "POK", "PWRGD", "PGD", "GOOD", "FB", "VFB", "SNS", "SENSE", "MON",
    "ADC", "DET", "CTRL", "CTL", "ON", "OFF", "SHDN", "RUN", "FLT", "FAULT", "ALERT", "INT", "LED", "SEL",
    "SET", "STAT", "STATUS", "TRIG", "RST", "RESET", "OK", "UV", "OV", "ILIM", "SS", "TRK", "TRACK", "SW", "LX",
    "SWN", "SWNODE", "BST", "BOOT", "PHASE",
}
_GENERIC_SUPPLY = re.compile(r"^(?:VCC|VDD|V|P|PWR|SUPPLY|RAIL|VOUT|OUT)$")

_AUTO_NET = re.compile(
    r"^(?:Net[A-Za-z]+\d+[A-Za-z]?_[A-Za-z0-9]+|Net-\(.*\)|unconnected-\(.*\)|N\$\d+|N\d{5,}|\$\$\$\d+|"
    r"NET\d{4,}|Net\d+)$"
)
_UNCONNECTED_NAMES = {"", "N/C", "?", "NO_NET", "<NO NET>", "(NO NET)"}

_RESET_TOKEN = re.compile(r"^[NX]?(?:RST|RESET|NRST|RSTN|POR|PORST|XRES|SRST|MRST|SYSRST)(?:N|B|L|\d)?$")
_I2C_DATA = re.compile(r"^(?:I2C\d*)?(?:SDA|SMBDAT|SMBDATA|TWD)\d*$")
_I2C_CLOCK = re.compile(r"^(?:I2C\d*)?(?:SCL|SMBCLK|TWCK)\d*$")


def leaf(name: str) -> str:
    """Last segment of a hierarchical net name (KiCad /sheet/net)."""
    s = name.strip()
    return s.rsplit("/", 1)[-1] if "/" in s.strip("/") and s.startswith("/") else s


def tokens(name: str) -> list[str]:
    """Upper-case tokens of a net or pin name, split on separators."""
    out: list[str] = []
    for t in _SEP.split(leaf(name).upper()):
        out += [p for p in _DOT.split(t) if p]
    return out


def is_unconnected_name(name: str | None) -> bool:
    """True for names tools use to mean no net (N/C, ?, empty)."""
    return name is None or name.strip().upper() in _UNCONNECTED_NAMES


def is_auto_named(name: str) -> bool:
    """True when the name looks generated by the CAD tool rather than given by a person."""
    return bool(_AUTO_NET.match(leaf(name)))


def _has_control(toks: list[str], allow: frozenset[str] = frozenset()) -> bool:
    return any(t in _CONTROL_WORDS and t not in allow for t in toks)


def is_ground_name(name: str) -> bool:
    """True for signal or power ground names (GND, AGND, PGND, GND_ISO, VSS, 0V)."""
    toks = tokens(name)
    return any(_GROUND_TOKEN.match(t) for t in toks) and not _has_control(toks, frozenset({"SENSE", "SNS"}))


def is_chassis_name(name: str) -> bool:
    """True for chassis, earth or shield nets."""
    return any(_CHASSIS_TOKEN.match(t) for t in tokens(name))


def _volts(m: re.Match[str], tok: str) -> float:
    if m.group("a") is not None:
        v = float(f"{m.group('a')}.{m.group('b')}")
    elif m.group("c") is not None:
        v = float(m.group("c"))
    elif m.group("d") is not None:
        v = float(f"{m.group('d')}.{m.group('e')}")
    else:
        v = float(f"{m.group('f')}.{m.group('g') or '0'}")
    return -v if tok.startswith("-") or m.group("sign") == "N" else v


def voltage_of(name: str) -> float | None:
    """Voltage encoded in a rail name: 3V3, +3.3V, P3V3, V3P3, 3V3A, 1V8_SW, -5V, N5V."""
    toks = tokens(name)
    for i, tok in enumerate(toks):
        m = _VOLT_TOKEN.match(tok)
        if m:
            v = _volts(m, tok)
            return -abs(v) if i == 0 and leaf(name).lstrip().startswith("-") else v
    return None


def is_rail_name(name: str) -> bool:
    """True when the name reads as a supply rail and not a control signal for one."""
    toks = tokens(name)
    if not toks or is_ground_name(name) or _has_control(toks):
        return False
    return voltage_of(name) is not None or any(_SUPPLY_WORDS.match(t) for t in toks)


def rail_keys(name: str) -> tuple[str, str]:
    """Strict and loose keys for spotting near-duplicate rail names (3V3, +3V3, 3.3V, VCC_3V3)."""
    out = []
    neg = leaf(name).lstrip().startswith("-")
    for tok in tokens(name):
        m = _VOLT_TOKEN.match(tok)
        if m:
            v = _volts(m, tok)
            whole, _, frac = f"{abs(v):g}".partition(".")
            out.append(("N" if v < 0 or neg else "") + f"{whole}V{frac}" + m.group("suffix"))
            neg = False
        else:
            out.append(tok.strip("+"))
    strict = "".join(out)
    loose = "".join(t for t in out if not _GENERIC_SUPPLY.match(t))
    return strict, loose


def net_kind(name: str) -> str:
    """Coarse net kind from the name: ground, chassis, rail or signal."""
    if is_ground_name(name):
        return "ground"
    if is_chassis_name(name):
        return "chassis"
    if is_rail_name(name):
        return "rail"
    return "signal"


def is_reset_name(name: str) -> bool:
    """True when a token of the name is a reset (RST, nRESET, RSTn, POR, XRES)."""
    return any(_RESET_TOKEN.match(t) for t in tokens(name))


def i2c_role(name: str) -> str:
    """'sda', 'scl' or '' from a net name."""
    for tok in tokens(name):
        if _I2C_DATA.match(tok):
            return "sda"
        if _I2C_CLOCK.match(tok):
            return "scl"
    return ""


def pin_core(name: str) -> str:
    """Pin name with active-low marks and KiCad overbar syntax removed, upper case."""
    s = (name or "").upper().replace("~{", "").replace("}", "")
    return s.strip().lstrip("~/!#*").rstrip("#*")


_PIN_ROLES: dict[str, re.Pattern[str]] = {
    "nc": re.compile(r"^(?:NC|N\.C\.|N/C|DNC|DNU|RSVD|RESERVED|NC\d{1,3}|NIC|DU)$"),
    "sw": re.compile(r"^(?:(?:SW|LX|SWN|SWO|SWNODE)(?:\d{1,2}|_?[A-D])?|PH)$"),
    "boot": re.compile(r"^(?:BST|BOOT|CB|CBOOT|BOOST|BS|VBST|CBST)(?:\d{1,2}|_?[A-D])?$"),
    "fb": re.compile(r"^(?:V?FB[A-Z]?|ADJ|FBK|VOS|VSENSE|VOUTS|VOUT_?S|VSNS|FB_?\d{1,2}|VFB\d{1,2})$"),
    "en": re.compile(r"^(?:N_?)?(?:EN|ENA|ENABLE|RUN|SHDN|ON|CE|ON_?OFF|EN\d{1,2}|RUN\d{1,2})(?:_?N|_?B|_?L)?$"),
    "pg": re.compile(r"^(?:PG|PGOOD|POK|PWRGD|PWR_?GD|PGD|PG\d{1,2}|PGOOD\d{1,2})$"),
    "ground": re.compile(
        r"^(?:[ADPSE]|ISO|SIG|PWR)?(?:GND|VSS)(?:[ADPSE]|IO|ISO|PWR|_?\d{1,3}|_[A-Z0-9]{1,6})?$|^[ADP]VSS\w*$"
    ),
    "pad": re.compile(r"^(?:E?PAD|EP|EPAD|THERMAL(?:_?PAD)?|TAB|TPAD|PAD\d*|EP\d*)$"),
    "vin": re.compile(r"^(?:P?VIN\d?|IN|VCC\w*|VDD\w*|AVDD\w*|DVDD\w*|IOVDD|PVDD\w*|VBAT|V\+|VSUP|VSYS|VIO|PVCC)$"),
    "reset": re.compile(r"^(?:N|X)?(?:RST|RESET|NRST|MR|XRES|POR|SRST|WDO|RSTN|RESETN|RST_?N|RESET_?N)\d{0,2}$"),
    "sda": re.compile(r"^(?:I2C\d?_?)?(?:SDA|SMBDAT|SMBDATA)\d?$"),
    "scl": re.compile(r"^(?:I2C\d?_?)?(?:SCL|SMBCLK)\d?$"),
    "xtal": re.compile(
        r"^(?:X(?:TAL)?_?(?:IN|OUT|I|O)\d?|XI|XO|OSC\d*_?(?:IN|OUT)|XTAL\d?|XIN\d?|XOUT\d?|EXTAL|XTAL_?[PN]|"
        r"[HL]SE_?(?:IN|OUT))$"
    ),
    "strap": re.compile(
        r"^(?:BOOT\d?|MODE\d?|CFG\d?|CONFIG\d?|ADDR?\d?|ADD\d|AD\d|A\d|SEL\d?|STRAP\w*|PHYAD\d?|MDIX\w*|BOOTSEL\w*|MD\d)$"
    ),
    "osc_out": re.compile(r"^(?:OUT|CLK|CLKOUT|OUTPUT|FOUT|CLK_?OUT)$"),
}
_PIN_SEGMENT = re.compile(r"[-/,\s]+")


def _segments(core: str) -> list[str]:
    parts = [p for p in _PIN_SEGMENT.split(core) if p]
    return [core] + parts if len(parts) > 1 else [core]


def pin_is(name: str, role: str) -> bool:
    """True when the pin name, or one of its '-' or '/' segments, matches the role pattern."""
    core = pin_core(name)
    pat = _PIN_ROLES.get(role)
    return bool(core and pat and any(pat.match(s) for s in _segments(core)))


def pin_role(name: str) -> str:
    """First matching role for a pin name, or '' when the name says nothing."""
    core = pin_core(name)
    if not core or core == "~":
        return ""
    for role in _PIN_ROLES:
        if pin_is(core, role):
            return role
    return ""
